// Renders the reference frontend's refusal wording map into C# data.
//
// The kernel refuses with a dotted code; which sentence a reader sees is the
// frontend's decision. `desktop/frontend-next/src/i18n/kernel.ts` holds that
// decision as `code -> message key`, and the message tables hold the wording.
// Retyping the map here would drift the moment either side edited one, so it is
// read from the source of truth and written out as data.
//
// Run: node desktop/avalonia/tools/render-refusals.mjs
// Check: node desktop/avalonia/tools/render-refusals.mjs -check
//
// Outputs: desktop/avalonia/src/Reasonix.Studio.Pages/I18n/RefusalSaid*.g.cs
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const SOURCE = join(HERE, "..", "..", "frontend-next", "src", "i18n", "kernel.ts");
const OUT = join(HERE, "..", "src", "Reasonix.Studio.Pages", "I18n");

/** Entries per file. One entry is one line, and the header and docs are ~40. */
const CHUNK = 600;

const HEADER = "// Code generated by desktop/avalonia/tools/render-refusals.mjs. DO NOT EDIT.";

/** Escapes a value as a C# regular string literal. */
function quote(value) {
    return '"' + value.replace(/\\/g, "\\\\").replace(/"/g, '\\"') + '"';
}

/** Reads the `SAID` map out of the reference frontend's kernel table. */
function readSaid() {
    const text = readFileSync(SOURCE, "utf8");
    const start = text.indexOf("const SAID");
    if (start < 0) {
        throw new Error(`${SOURCE}: no SAID map`);
    }

    const end = text.indexOf("\n};", start);
    if (end < 0) {
        throw new Error(`${SOURCE}: SAID map is not closed`);
    }

    // Comments carry explanation and no entries; an entry may wrap onto a second
    // line, which is why the pair is matched rather than the line.
    const body = text.slice(start, end).replace(/\/\/[^\r\n]*/g, "");
    const entry = /"([a-z0-9_.]+)"\s*:\s*"([a-z0-9_.]+)"/g;

    const entries = [];
    const seen = new Set();
    let match;
    while ((match = entry.exec(body)) !== null) {
        const [, code, key] = match;
        if (seen.has(code)) {
            throw new Error(`SAID repeats ${code}`);
        }

        seen.add(code);
        entries.push({ code, key });
    }

    if (entries.length === 0) {
        throw new Error(`${SOURCE}: SAID map holds no entries`);
    }

    entries.sort((a, b) => (a.code < b.code ? -1 : a.code > b.code ? 1 : 0));
    return entries;
}

/** Renders one chunk's table. */
function renderChunk(name, entries, part, parts) {
    const lines = [
        HEADER,
        "using System.Collections.Generic;",
        "",
        "namespace Reasonix.Studio.Pages.I18n;",
        "",
        "/// <summary>",
        `/// Refusal code to message key, part ${part} of ${parts}.`,
        "/// </summary>",
        "/// <remarks>",
        "/// Which sentence a reader sees is this interface's decision, not the",
        "/// kernel's; the kernel only says what happened. Both sides are read from",
        "/// the reference frontend's own table, and this file is written by the",
        "/// generator rather than by hand.",
        "/// </remarks>",
        `internal static class ${name}`,
        "{",
        "    /// <summary>",
        "    /// Gets the part's table, keyed by the code the kernel sends.",
        "    /// </summary>",
        "    public static IReadOnlyDictionary<string, string> Table { get; } =",
        "        new Dictionary<string, string>(System.StringComparer.Ordinal)",
        "        {",
    ];

    for (const { code, key } of entries) {
        lines.push(`            [${quote(code)}] = ${quote(key)},`);
    }

    lines.push("        };", "}", "");
    return { name: `${name}.g.cs`, text: lines.join("\r\n") };
}

/** Renders the merged table the lookup reads. */
function renderMerged(chunks) {
    const lines = [
        HEADER,
        "using System.Collections.Generic;",
        "",
        "namespace Reasonix.Studio.Pages.I18n;",
        "",
        "/// <summary>",
        "/// Every refusal code this interface has wording for, in one table.",
        "/// </summary>",
        "/// <remarks>",
        "/// The chunks stay separate so a review of one area reads one file; this",
        "/// merges them once, for the lookup a refusal makes by code alone.",
        "/// </remarks>",
        "internal static class RefusalSaid",
        "{",
        "    /// <summary>",
        "    /// Gets the message key for each code, keyed by the code itself.",
        "    /// </summary>",
        "    public static IReadOnlyDictionary<string, string> ByCode { get; } = Merge();",
        "",
        "    /// <summary>",
        "    /// Builds the merged table from the chunks.",
        "    /// </summary>",
        "    /// <returns>The merged table.</returns>",
        "    private static Dictionary<string, string> Merge()",
        "    {",
        "        var all = new Dictionary<string, string>(System.StringComparer.Ordinal);",
    ];

    for (const name of chunks) {
        lines.push(`        foreach (var entry in ${name}.Table)`);
        lines.push("        {");
        lines.push("            all[entry.Key] = entry.Value;");
        lines.push("        }");
    }

    lines.push("        return all;", "    }", "}", "");
    return { name: "RefusalSaid.g.cs", text: lines.join("\r\n") };
}

/** Writes or checks the rendered files. */
function main() {
    const check = process.argv.includes("-check");
    const entries = readSaid();
    const parts = Math.ceil(entries.length / CHUNK);
    const chunks = [];
    const files = [];

    for (let index = 0; index < parts; index += 1) {
        const name = `RefusalSaid${index + 1}`;
        chunks.push(name);
        files.push(renderChunk(name, entries.slice(index * CHUNK, (index + 1) * CHUNK), index + 1, parts));
    }

    files.push(renderMerged(chunks));

    const stale = [];
    let written = 0;
    for (const file of files) {
        const path = join(OUT, file.name);
        const current = existsSync(path) ? readFileSync(path, "utf8") : null;
        if (current === file.text) continue;
        if (check) {
            stale.push(file.name);
            continue;
        }

        writeFileSync(path, file.text, "utf8");
        written += 1;
    }

    if (check) {
        if (stale.length > 0) {
            for (const name of stale) console.error(`stale: ${name}`);
            console.error(`${stale.length} refusal file(s) are out of date; run node desktop/avalonia/tools/render-refusals.mjs`);
            process.exit(1);
        }

        console.log(`Refusal wording is up to date: ${entries.length} codes in ${files.length} files.`);
        return;
    }

    console.log(`Rendered ${entries.length} codes into ${files.length} files (${written} written).`);
}

main();
