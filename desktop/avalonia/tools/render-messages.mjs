// Renders the reference frontend's message tables into C# data files.
//
// The interface's wording lives in `desktop/frontend-next/src/i18n/msg/*.ts` as
// one table per area, each entry holding the Chinese and the English side by
// side. A replacement shell that retyped those strings would drift the moment
// either side edited one, so they are read from the source of truth and written
// out as data.
//
// Run: node desktop/avalonia/tools/render-messages.mjs
// Check: node desktop/avalonia/tools/render-messages.mjs -check
//
// Outputs: desktop/avalonia/src/Reasonix.Studio.Pages/I18n/Messages.<Area>.g.cs
//
// One file per area, split when an area outgrows the repository's 800-line
// ceiling for one responsibility. Each file is a table, not a member per key:
// the keys number in the thousands, and one constant each would spend three
// lines of XML documentation per phrase to restate the phrase.
import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const SOURCE = join(HERE, "..", "..", "frontend-next", "src", "i18n", "msg");
const OUT = join(HERE, "..", "src", "Reasonix.Studio.Pages", "I18n");

/** Entries per file. One entry is one line, and the header and docs are ~40. */
const CHUNK = 600;

/** Files in the message directory that hold no messages. */
const SKIPPED = new Set(["index.ts", "types.ts"]);

/** Turns `workbench` into `Workbench`. */
function typeName(area) {
  return area
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
}

/** Escapes a value as a C# regular string literal. */
function quote(value) {
  return '"' + value.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\r/g, "\\r").replace(/\n/g, "\\n").replace(/\t/g, "\\t") + '"';
}

/** Reads every message table in the source directory. */
async function readTables() {
  const files = readdirSync(SOURCE).filter((name) => name.endsWith(".ts") && !name.endsWith(".test.ts") && !SKIPPED.has(name));
  const entries = [];

  for (const file of files.sort()) {
    const module = await import(`file:///${SOURCE.replace(/\\/g, "/")}/${file}`);
    for (const table of Object.values(module)) {
      if (!table || typeof table !== "object") continue;
      for (const [key, message] of Object.entries(table)) {
        if (typeof message?.zh !== "string" || typeof message?.en !== "string") {
          throw new Error(`${file}: ${key} is not { zh, en }`);
        }

        entries.push({ key, zh: message.zh, en: message.en, file });
      }
    }
  }

  const seen = new Map();
  for (const entry of entries) {
    const previous = seen.get(entry.key);
    if (previous) {
      throw new Error(`${entry.file} repeats ${entry.key} from ${previous.file}`);
    }

    seen.set(entry.key, entry);
  }

  entries.sort((a, b) => (a.key < b.key ? -1 : a.key > b.key ? 1 : 0));
  return entries;
}

/** Groups the entries by the area their key names, then into chunks. */
function group(entries) {
  const areas = new Map();
  for (const entry of entries) {
    const dot = entry.key.indexOf(".");
    const area = dot > 0 ? entry.key.slice(0, dot) : "misc";
    if (!areas.has(area)) areas.set(area, []);
    areas.get(area).push(entry);
  }

  const files = [];
  for (const [area, list] of [...areas].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))) {
    const chunks = Math.ceil(list.length / CHUNK);
    for (let index = 0; index < chunks; index += 1) {
      const name = chunks === 1 ? typeName(area) : `${typeName(area)}${index + 1}`;
      files.push({ name, area, entries: list.slice(index * CHUNK, (index + 1) * CHUNK), part: index + 1, parts: chunks });
    }
  }

  return files;
}

/** Renders one file. */
function render(file) {
  const lines = [
    "// Code generated by desktop/avalonia/tools/render-messages.mjs. DO NOT EDIT.",
    "using System.Collections.Generic;",
    "",
    "namespace Reasonix.Studio.Pages.I18n;",
    "",
    "/// <summary>",
    `/// Message table for the <c>${file.area}</c> area${file.parts > 1 ? `, part ${file.part} of ${file.parts}` : ""}.`,
    "/// </summary>",
    "/// <remarks>",
    "/// Both languages travel together so neither can be read without the other in",
    "/// view. The keys and the wording come from the reference frontend's own table,",
    "/// and this file is written by the generator rather than by hand.",
    "/// </remarks>",
    `internal static class Messages${file.name}`,
    "{",
    "    /// <summary>",
    "    /// Gets the table, keyed the way the interface names a message.",
    "    /// </summary>",
    "    public static IReadOnlyDictionary<string, (string Zh, string En)> Table { get; } =",
    "        new Dictionary<string, (string Zh, string En)>(System.StringComparer.Ordinal)",
    "        {",
  ];

  for (const entry of file.entries) {
    lines.push(`            [${quote(entry.key)}] = (${quote(entry.zh)}, ${quote(entry.en)}),`);
  }

  lines.push("        };", "}", "");
  return { name: `Messages${file.name}.g.cs`, text: lines.join("\r\n") };
}

/** Renders every file. */
function renderAll(files) {
  const rendered = files.map(render);

  // One merged table, so the shell's lookup does not walk the generated classes
  // by reflection: a static list is what the compiler can check and what AOT can
  // keep. The order is the area order, and a duplicate key is impossible because
  // `readTables` already refused one.
  const lines = [
    "// Code generated by desktop/avalonia/tools/render-messages.mjs. DO NOT EDIT.",
    "using System.Collections.Generic;",
    "",
    "namespace Reasonix.Studio.Pages.I18n;",
    "",
    "/// <summary>",
    "/// Every message the interface can name, in one table.",
    "/// </summary>",
    "/// <remarks>",
    "/// The per-area tables stay separate so a review of one area reads one file;",
    "/// this merges them once, for the lookup a call site makes by key alone.",
    "/// </remarks>",
    "internal static class MessageTables",
    "{",
    "    /// <summary>",
    "    /// Gets every message, keyed the way the interface names it.",
    "    /// </summary>",
    "    public static IReadOnlyDictionary<string, (string Zh, string En)> All { get; } = Merge();",
    "",
    "    /// <summary>",
    "    /// Builds the merged table from the per-area ones.",
    "    /// </summary>",
    "    /// <returns>The merged table.</returns>",
    "    private static Dictionary<string, (string Zh, string En)> Merge()",
    "    {",
    "        var all = new Dictionary<string, (string Zh, string En)>(System.StringComparer.Ordinal);",
  ];

  for (const file of files) {
    lines.push(`        foreach (var entry in Messages${file.name}.Table)`);
    lines.push("        {");
    lines.push("            all[entry.Key] = entry.Value;");
    lines.push("        }");
  }

  lines.push("        return all;", "    }", "}", "");
  rendered.push({ name: "MessageTables.g.cs", text: lines.join("\r\n") });
  return rendered;
}

/** Writes or checks the rendered files. */
async function main() {
  const check = process.argv.includes("-check");
  const entries = await readTables();
  const files = renderAll(group(entries));

  mkdirSync(OUT, { recursive: true });

  const stale = [];
  let written = 0;
  for (const file of files) {
    const path = join(OUT, file.name);
    const current = existsSync(path) ? readFileSync(path, "utf8") : null;
    if (current === file.text) continue;
    if (check) {
      stale.push(file.name);
      continue;
    }

    writeFileSync(path, file.text, "utf8");
    written += 1;
  }

  if (check) {
    if (stale.length > 0) {
      for (const name of stale) console.error(`stale: ${name}`);
      console.error(`${stale.length} message file(s) are out of date; run node desktop/avalonia/tools/render-messages.mjs`);
      process.exit(1);
    }

    console.log(`Messages are up to date: ${entries.length} entries in ${files.length} files.`);
    return;
  }

  console.log(`Rendered ${entries.length} entries into ${files.length} files (${written} written).`);
}

await main();
