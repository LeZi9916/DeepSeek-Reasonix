package main

import (
	"testing"
)

// csRecordSource is one generated record, shaped the way tools/wiregen writes
// it: a JsonPropertyName attribute above each property, and the C# name beside
// it rather than as the wire name.
const csRecordSource = `// Code generated by tools/wiregen. DO NOT EDIT.

namespace Reasonix.Studio.Contracts.Wire;

/// <summary>
/// Attachment is the JSON form of a stored image a message references.
/// </summary>
public sealed record Attachment
{
    /// <summary>
    /// Path carries the kernel's "path" value.
    /// </summary>
    [JsonPropertyName("path")]
    public string Path { get; init; }

    /// <summary>
    /// Root carries the kernel's "root" value.
    /// </summary>
    [JsonPropertyName("root")]
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    public string Root { get; init; }
}
`

// The wire name is what a payload carries, not the C# property name, so reading
// the JsonPropertyName attribute is what makes the comparison about the contract.
func TestCsRecordFieldsReadsWireNames(t *testing.T) {
	fields, line, found := csRecordFields(csRecordSource, "Attachment")
	if !found {
		t.Fatal("Attachment is declared in this fixture")
	}
	if line != 8 {
		t.Fatalf("Attachment opens on line 8, got %d", line)
	}
	want := []string{"path", "root"}
	if len(fields) != len(want) {
		t.Fatalf("want %v, got %v", want, fields)
	}
	for i, name := range want {
		if fields[i] != name {
			t.Fatalf("want %v, got %v", want, fields)
		}
	}
}

// A record the fixture does not declare has to be reported as absent rather than
// answered with an empty field list, which would read as a faithful mirror of a
// kernel type that sends nothing.
func TestCsRecordFieldsRefusesAnUndeclaredRecord(t *testing.T) {
	if _, _, found := csRecordFields(csRecordSource, "Missing"); found {
		t.Fatal("a record this fixture does not declare must not be found")
	}
}

// The defect this check exists for: the kernel sends a field the generated
// record does not read. A shell that cannot read it draws the default and says
// nothing, so the comparison has to name it.
func TestWiregenParityFindingsNamesAFieldTheRecordCannotRead(t *testing.T) {
	files := map[string]string{
		"Attachment.g.cs": csRecordSource,
	}
	mirrors := []wireMirror{{"internal/contract/eventwire/attachment.go", "Attachment", "", "Attachment"}}
	goFields := map[string][]string{
		"internal/contract/eventwire/attachment.go.Attachment": {"path", "root", "sha256"},
	}

	got := wiregenParityFindingsFrom(files, mirrors, goFields)
	if len(got) != 1 {
		t.Fatalf("want one finding, got %+v", got)
	}
	if got[0].Rule != ruleWireParity {
		t.Fatalf("want rule %s, got %s", ruleWireParity, got[0].Rule)
	}
}

// The other direction: a generated record that reads a name nothing sends. This
// is what a Go struct losing a field without regeneration looks like.
func TestWiregenParityFindingsNamesAFieldNothingSends(t *testing.T) {
	files := map[string]string{
		"Attachment.g.cs": csRecordSource,
	}
	mirrors := []wireMirror{{"internal/contract/eventwire/attachment.go", "Attachment", "", "Attachment"}}
	goFields := map[string][]string{
		"internal/contract/eventwire/attachment.go.Attachment": {"path"},
	}

	got := wiregenParityFindingsFrom(files, mirrors, goFields)
	if len(got) != 1 {
		t.Fatalf("want one finding, got %+v", got)
	}
}

// A pair whose record was never rendered is skipped: the mirror table covers
// serve and control views outside the event contract, and those keep their
// TypeScript mirror until the shell replaces it.
func TestWiregenParityFindingsSkipsUnrenderedRecords(t *testing.T) {
	mirrors := []wireMirror{{"internal/frontend/serve/side.go", "SideProgress", "", "SideProgress"}}
	goFields := map[string][]string{
		"internal/frontend/serve/side.go.SideProgress": {"phase"},
	}

	if got := wiregenParityFindingsFrom(map[string]string{}, mirrors, goFields); len(got) != 0 {
		t.Fatalf("an unrendered pair is not a finding, got %+v", got)
	}
}
